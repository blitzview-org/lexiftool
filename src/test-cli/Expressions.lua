--------------------------------------------------------------------------------
-- File:         test-cli/Expressions.lua
--
-- Description:  Perl expressions from real exiftool command lines -- the data
--               of the CLI golden group "expr" (Cases.EXPR, doc/cli-tests.md,
--               "Expression corpus").
--
--               Each entry is an expression as people actually write it: an
--               -if condition, an advanced formatting string ("${TAG;EXPR}",
--               the right-hand side of a "-TAG<..." copy, a -p format) or a
--               -api Filter, taken verbatim from the exiftool documentation,
--               the ExifTool forum, Stack Exchange sites, blogs and gists --
--               including posts whose expression does not work as their
--               author hoped (shell-quoting slips, wrong operators): what
--               exiftool makes of those is part of its behaviour too.
--               Nothing here is invented; an entry that has to differ from
--               its source says so (variant/why).
--
--               Attribution: `src` is the page the expression was taken
--               from. Snippets from Stack Exchange sites are licensed under
--               CC BY-SA (https://stackoverflow.com/help/licensing); the
--               source link is their attribution.
--
--               Fields:
--                 id       stable case name: the case label is "x-" .. id;
--                          a new entry takes the next free number of its
--                          kind, existing ids never change
--                 kind     if     -- run as  -if EXPR -p '$filename' DIR
--                          fmt, assign, p, other
--                                 -- run as  -p EXPR DIR
--                          api    -- run as  -api OPTION=EXPR -S TAGS DIR
--                                    (see Expressions.API_TAGS)
--                 option   (api) the API option the expression is for
--                 opts     options the source command line gives along with
--                          the expression, put in front (-userParam ...)
--                 expr     the expression, verbatim
--                 variant  what is run instead, when the expression itself
--                          cannot give a reproducible result; why says why
--                 skip     the reason an entry is not run
--                 src      source URL
--                 note     what the source uses the expression for
--------------------------------------------------------------------------------

