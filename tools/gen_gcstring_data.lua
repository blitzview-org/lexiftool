--------------------------------------------------------------------------------
-- File:         tools/gen_gcstring_data.lua
--
-- Description:  Generate src/lexiftool/GCStringData.lua, the character
--               properties behind lexiftool.perl's Unicode::GCString
--               (`columns`, the display width exiftool uses to align -lang
--               output), from the character database of the Perl module
--               Unicode::LineBreak (CPAN distribution Unicode-LineBreak,
--               whose bundled sombok library implements Unicode::GCString).
--
--               sombok compiles UAX #11 (East Asian Width, with its own
--               zero-width classes Z/ZA/ZW for marks and format characters)
--               and UAX #29 (Grapheme_Cluster_Break) plus UAX #14 (the line
--               breaking class, of which GCString needs only SP) into a
--               compact array in sombok/lib/<UNICODE_VERSION>.c. This tool
--               reads that file -- the data the Perl module itself uses, so
--               the port measures exactly as a Perl with Unicode::LineBreak
--               installed -- and writes the properties of every code point
--               below U+20000 as a run-length list: `starts` (first code
--               point of each run) and `props` (its property value,
--               kind * 3 + columns, as the generated file lists the kinds). Code points
--               from U+20000 on are sombok's fixed blocks (Han, tags,
--               variation selectors, private use, reserved), which
--               lexiftool.perl handles itself as linebreak_charprop does.
--
-- Syntax:       <interp> tools/gen_gcstring_data.lua \
--                   <Unicode-LineBreak>/sombok/lib/<version>.c
--               (run from the repository root; the distribution is the one
--               on CPAN, https://metacpan.org/dist/Unicode-LineBreak; the
--               version file named by its UNICODE_VERSION, the newest in
--               sombok/lib, is the one the module is built with)
--------------------------------------------------------------------------------

local src = arg[1]
if not src then
    io.stderr:write('usage: tools/gen_gcstring_data.lua <Unicode-LineBreak>/sombok/lib/<version>.c\n')
    os.exit(2)
end
local fh = assert(io.open(src, 'rb'))
local text = fh:read('a')
fh:close()

local version = assert(text:match('#define UNICODE_VERSION "([^"]+)"'), 'no UNICODE_VERSION')
-- (the distribution's release, from its unpacked directory name)
local release = assert(src:match('Unicode%-LineBreak%-([%d.]+)[/\\]'),
                       'run on the file inside an unpacked Unicode-LineBreak-<release> directory')

-- the comma-separated body of a C array definition
local function arrayBody(name)
    local body = text:match(name .. '%[%]%s*=%s*(%b{})')
    assert(body, 'array ' .. name .. ' not found')
    return body:sub(2, -2)
end

local index = {}
for n in arrayBody('linebreak_prop_index'):gmatch('%d+') do index[#index + 1] = tonumber(n) end
local entries = {}
for tok in arrayBody('linebreak_prop_array'):gmatch('[%w_]+') do entries[#entries + 1] = tok end
assert(#entries % 4 == 0, 'linebreak_prop_array is not made of 4-tuples')

-- property kinds (Grapheme_Cluster_Break as sombok's _gcinfo distinguishes
-- them; SP is a character of line breaking class SP, which never takes
-- extenders under Unicode::GCString's default options)
local KIND = {
    GB_Other = 0, GB_OtherLetter = 0,
    GB_CR = 1, GB_LF = 2, GB_Control = 3,
    GB_Extend = 4, GB_SpacingMark = 4, GB_Virama = 4,
    GB_Prepend = 5,
    GB_L = 6, GB_V = 7, GB_T = 8, GB_LV = 9, GB_LVT = 10,
    GB_Regional_Indicator = 11,
}
local KIND_SP = 12
-- columns of an East Asian Width class (sombok's eaw2col without the
-- EastAsian context option: ambiguous is narrow)
local COLS = { EA_Z = 0, EA_ZA = 0, EA_ZW = 0, EA_F = 2, EA_W = 2,
               EA_Na = 1, EA_N = 1, EA_A = 1, EA_H = 1 }

local BLKLEN = 5
local starts, props = {}, {}
local last
for c = 0, 0x1FFFF do
    local e = (index[(c >> BLKLEN) + 1] + (c & ((1 << BLKLEN) - 1))) * 4
    local lbc, eaw, gcb = entries[e + 1], entries[e + 2], entries[e + 3]
    local kind = KIND[gcb]
    assert(kind, 'unknown GCB value ' .. tostring(gcb) .. ' at ' .. c)
    if lbc == 'LB_SP' then
        assert(kind == 0, 'SP character with a GCB other than Other')
        kind = KIND_SP
    end
    local cols = COLS[eaw]
    assert(cols, 'unknown EA value ' .. tostring(eaw) .. ' at ' .. c)
    local p = kind * 3 + cols
    if p ~= last then
        starts[#starts + 1] = c
        props[#props + 1] = p
        last = p
    end
end

local out = {}
out[#out + 1] = '-- generated by tools/gen_gcstring_data.lua from Unicode-LineBreak-' .. release
out[#out + 1] = '-- sombok/lib/' .. version .. '.c - do not edit'
out[#out + 1] = '-- luacheck: ignore'
out[#out + 1] = 'return {'
out[#out + 1] = "    LINEBREAK_VERSION = '" .. release .. "',"
out[#out + 1] = "    UNICODE_VERSION = '" .. version .. "',"
out[#out + 1] = '    -- property value = kind * 3 + columns; kinds:'
out[#out + 1] = '    --   0 Other, 1 CR, 2 LF, 3 Control, 4 Extend/SpacingMark/Virama,'
out[#out + 1] = '    --   5 Prepend, 6 L, 7 V, 8 T, 9 LV, 10 LVT, 11 Regional_Indicator,'
out[#out + 1] = '    --   12 SP (line breaking class SP)'
local function list(name, t)
    out[#out + 1] = '    ' .. name .. ' = {'
    local line = {}
    for i = 1, #t do
        line[#line + 1] = tostring(t[i])
        if #line == 16 then
            out[#out + 1] = '        ' .. table.concat(line, ',') .. ','
            line = {}
        end
    end
    if #line > 0 then out[#out + 1] = '        ' .. table.concat(line, ',') .. ',' end
    out[#out + 1] = '    },'
end
list('starts', starts)
list('props', props)
out[#out + 1] = '}'

local dst = 'src/lexiftool/GCStringData.lua'
local of = assert(io.open(dst, 'wb'))
of:write(table.concat(out, '\n'), '\n')
of:close()
print(string.format('%s: Unicode %s, %d runs', dst, version, #starts))
