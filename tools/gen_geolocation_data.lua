--------------------------------------------------------------------------------
-- File:         tools/gen_geolocation_data.lua
--
-- Description:  Generate src/lexiftool/GeolocationData.lua from
--               src/lexiftool/Geolocation.dat: a plain Lua module whose sole
--               content is `return "<the file's bytes>"`, quoted with
--               string.format('%q', ...) so any byte sequence round-trips
--               exactly.
--
--               Why: Geolocation.lua used to find Geolocation.dat by its own
--               chunk name (debug.getinfo), the same idea as upstream's
--               %INC-based lookup -- but on Windows, require() builds that
--               chunk name with a backslash where the module path's dot was,
--               while the pattern that looked for the file expected a
--               forward slash, so the database was silently never found
--               (lexiftool.Geolocation.ReadDatabase never ran). Loading the
--               bundled database as an ordinary Lua module instead goes
--               through require()/package.path like every other module, on
--               every platform, and (as a C API/standalone bonus) is a
--               generated module like any other that the launcher's
--               bytecode machinery already covers without special-casing
--               the .dat file (see standalone/genembed.lua).
--
--               Like src/lexiftool/TagLookup.lua's generated section (see
--               tools/gen_tag_lookup.lua), the result is committed, not a
--               build/ artifact: it is read by plain require() with no
--               build step, exactly as Geolocation.dat itself was. Re-run
--               this script whenever Geolocation.dat is updated from the
--               vendored upstream (a new ExifTool release with a newer
--               geolocation database).
--
--               The lexiftool_options.geoDir override (Perl's
--               $Image::ExifTool::Geolocation::directory, an explicit
--               directory set by the caller) keeps reading a real
--               Geolocation.dat file by path -- that path is supplied by
--               the caller, not derived from a chunk name, so it was never
--               exposed to the bug above.
--
-- Syntax:       <interp> tools/gen_geolocation_data.lua
--               (run from the repository root; package.path not needed)
--------------------------------------------------------------------------------

local SRC = 'src/lexiftool/Geolocation.dat'
local DST = 'src/lexiftool/GeolocationData.lua'

local f = assert(io.open(SRC, 'rb'), 'cannot open ' .. SRC)
local data = f:read('a')
f:close()
assert(#data > 0, SRC .. ' is empty')

local quoted = string.format('%q', data)
local out = assert(io.open(DST, 'wb'))
out:write('-- generated by tools/gen_geolocation_data.lua from Geolocation.dat - do not edit\n')
out:write('-- luacheck: ignore\n')
out:write('return ', quoted, '\n')
out:close()

print(string.format('gen_geolocation_data: %s (%d bytes) -> %s (%d bytes)',
    SRC, #data, DST, #quoted))
